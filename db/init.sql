-- A typo in a slug or market name fails the whole file instead of dropping a rule
DO $$
DECLARE bad TEXT;
BEGIN
    SELECT string_agg(format('%s | %s | %s', r.market, r.market_category, r.slug), E'\n')
    INTO bad
    FROM rules r
    LEFT JOIN markets m ON m.name = r.market
    LEFT JOIN categories c ON c.slug = r.slug
    WHERE m.id IS NULL OR c.id IS NULL;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION E'Rules with an unknown market or slug:\n%', bad;
    END IF;
END $$;

INSERT INTO category_map (market_id, market_category, category_id)
SELECT m.id, r.market_category, c.id
FROM rules r
JOIN markets m ON m.name = r.market
JOIN categories c ON c.slug = r.slug;

