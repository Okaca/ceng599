-- The whole database: the scraper's tables, and the category tree the webapp reads.
--
-- Postgres runs this file by itself on the first start of an empty data volume.
-- Every statement is safe to repeat, so after editing the categories, apply it to
-- the running database without losing products or prices:
--
--   docker exec -i market_postgres sh -c 'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1' < db/init.sql
--
-- Only the category tables are rebuilt; markets, products and prices are kept.

CREATE TABLE IF NOT EXISTS markets (
    id    SERIAL PRIMARY KEY,
    name  TEXT UNIQUE NOT NULL
);

