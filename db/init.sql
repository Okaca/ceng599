-- One row per product per market: details that rarely change
CREATE TABLE IF NOT EXISTS products (
    id           SERIAL PRIMARY KEY,
    market_id    INT  NOT NULL REFERENCES markets(id),
    external_id  TEXT NOT NULL,          -- the market's own product id
    name         TEXT NOT NULL,
    brand        TEXT,
    barcode      TEXT,                   -- EAN, for cross-market matching
    category     TEXT,                   -- the market's own category name
    quantity     NUMERIC(10,3),          -- e.g. 500
    unit         TEXT,                   -- 'g', 'kg', 'ml', 'l', 'adet'
    url          TEXT,
    image_url    TEXT,
    UNIQUE (market_id, external_id)
);

CREATE INDEX IF NOT EXISTS idx_products_barcode ON products (barcode);

-- One row per product per store per day: the price history
CREATE TABLE IF NOT EXISTS prices (
    id             BIGSERIAL PRIMARY KEY,
    product_id     INT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    price          NUMERIC(10,2) NOT NULL,   -- what the customer pays
    regular_price  NUMERIC(10,2),            -- price before discount
    discount_rate  SMALLINT,                 -- e.g. 33 for %33
    in_stock       BOOLEAN NOT NULL DEFAULT TRUE,
    store_code     TEXT NOT NULL DEFAULT '', -- '' when the market has one price
    scraped_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- At most one price per product per store per (Istanbul) day, so a rerun
-- on the same day updates the row instead of adding a duplicate
CREATE UNIQUE INDEX IF NOT EXISTS uq_prices_daily ON prices (
    product_id, store_code, ((scraped_at AT TIME ZONE 'Europe/Istanbul')::date)
);

CREATE INDEX IF NOT EXISTS idx_prices_scraped_at ON prices (scraped_at);

-- Categories -----------------------------------------------------------------
-- Our own category tree, shared by all markets, and rules mapping each market's
-- categories onto it. Only the webapp reads these; the scraper keeps writing
-- products.category as the market names it.

-- main > sub, e.g. 'Süt & Kahvaltılık' > 'Peynir'. A subcategory exists only when every
-- market that sells those products keeps them apart; otherwise a market lumping them
-- together would be missing from it, and the comparison would be unfair.
CREATE TABLE IF NOT EXISTS categories (
    id         SERIAL PRIMARY KEY,
    parent_id  INT REFERENCES categories(id) ON DELETE CASCADE,  -- NULL for a main category
    name       TEXT NOT NULL,
    slug       TEXT UNIQUE NOT NULL,   -- the path, e.g. 'sut-kahvaltilik/peynir'
    position   INT  NOT NULL DEFAULT 0 -- display order among siblings
);

CREATE INDEX IF NOT EXISTS idx_categories_parent ON categories (parent_id);

-- A rule: products whose category is market_category, or anything below it
-- (market_category || ' > ...'), belong to category_id. The longest matching
-- rule wins, so 'İçecekler > Gazsız İçecekler > Ayran' can override 'İçecekler > Gazsız İçecekler'.
CREATE TABLE IF NOT EXISTS category_map (
    market_id        INT  NOT NULL REFERENCES markets(id),
    market_category  TEXT NOT NULL,
    category_id      INT  NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (market_id, market_category)
);

-- The view below reads the distinct (market, category) pairs of products
CREATE INDEX IF NOT EXISTS idx_products_market_category ON products (market_id, category);

-- Every market category that occurs in products, with the category it resolves to.
-- There are only a few thousand distinct market categories, so the prefix matching
-- runs over those instead of over every product. Categories no rule matches are absent.
CREATE OR REPLACE VIEW category_resolution AS
SELECT DISTINCT ON (c.market_id, c.category)
    c.market_id, c.category, m.category_id
FROM (SELECT DISTINCT market_id, category FROM products) c
JOIN category_map m
  ON m.market_id = c.market_id
 AND (c.category = m.market_category OR starts_with(c.category, m.market_category || ' > '))
ORDER BY c.market_id, c.category, length(m.market_category) DESC;

